"""Generate reproducible conservative point-response POWER lookup tables.

Offline only. No measured calibration, target class or scene-distance prior.
The runtime additionally groups all +/-2-bin returns regardless of angle.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

N=256
FC_HZ=62197840000.0
PITCH_M=.0025
U_STEP=1/1024
U_UNCERTAINTY=.0175
FRACTIONS=129

def make_tables():
    n=np.arange(N,dtype=np.float64)
    window=.5-.5*np.cos(2*np.pi*n/(N-1))
    ranges=np.zeros(N,dtype=np.float64)
    fractions=np.linspace(-.5,.5,FRACTIONS)
    for center in range(7,204):
        tones=np.exp(2j*np.pi*(center+fractions[:,None])*n/N)
        tones-=np.mean(tones,axis=1,keepdims=True)
        power=np.abs(np.fft.fft(tones*window,axis=1))**2
        peak=np.argmax(power,axis=1)
        power/=np.max(power,axis=1,keepdims=True)
        # Only actual non-wrapped bin separations are indexed by production.
        for row,anchor in zip(power,peak):
            np.maximum.at(ranges,np.abs(np.arange(N)-anchor),row)
    # Sampling pad plus the separate runtime +6dB/-24dB guards. This is a
    # sampled nominal-model envelope, not proof of arbitrary calibration error.
    ranges=np.minimum(1,ranges+1e-4)
    q=2*np.pi*PITCH_M*FC_HZ/299792458.0
    offsets=np.linspace(-U_UNCERTAINTY-U_STEP,U_UNCERTAINTY+U_STEP,257)
    angular=[]
    derivative_pad=7*q*(offsets[1]-offsets[0])/2
    for u in np.arange(2049)*U_STEP:
        a=np.exp(1j*q*(u+offsets[:,None])*np.arange(8)).mean(axis=1)
        angular.append(min(1,float(np.max(np.abs(a)**2))+derivative_pad))
    return ranges.astype('<f4'),np.asarray(angular,dtype='<f4')

def render(ranges,angular):
    sha=hashlib.sha256(ranges.tobytes()+angular.tobytes()).hexdigest()
    lines=['/* Generated by tools/generate_reflection_envelope.py; nominal power envelope. */',
           '#ifndef RADAR_REFLECTION_ENVELOPE_H','#define RADAR_REFLECTION_ENVELOPE_H',
           '#define RADAR_REFLECTION_ENVELOPE_SHA256 "'+sha+'"',
           '#define RADAR_REFLECTION_U_LOOKUP_SCALE 1024.0f',
           '#define RADAR_REFLECTION_GUARD_FACTOR 3.981071706f',
           '#define RADAR_REFLECTION_GUARD_FLOOR 0.003981071706f']
    for name,values in [('radar_reflection_range_envelope',ranges),('radar_reflection_u_envelope',angular)]:
        lines.append('static const float '+name+'['+str(len(values))+']={')
        for start in range(0,len(values),8):
            lines.append('    '+','.join(format(float(v),'.9e')+'f' for v in values[start:start+8])+',')
        lines.append('};')
    lines.extend(['#endif',''])
    return '\n'.join(lines),sha

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header',type=Path,required=True);p.add_argument('--manifest',type=Path,required=True)
    a=p.parse_args();r,u=make_tables();header,sha=render(r,u)
    a.header.parent.mkdir(parents=True,exist_ok=True);a.manifest.parent.mkdir(parents=True,exist_ok=True)
    a.header.write_text(header,encoding='ascii',newline='\n')
    manifest=dict(schema='M2_REFLECTION_ENVELOPE_V1',model='DC_REMOVE_HANN256_FFT_POWER_X_8ULA_POWER',
        ranges=256,angular=2049,range_centers=[7,203],fraction_positions=FRACTIONS,
        fc_hz=FC_HZ,pitch_m=PITCH_M,u_step=U_STEP,u_uncertainty=U_UNCERTAINTY,
        range_sampling_pad=1e-4,angular_derivative_pad=True,guard_db=6,guard_floor_db=-24,
        same_range_group_half_width_bins=2,tables_sha256=sha,
        header_sha256=hashlib.sha256(a.header.read_bytes()).hexdigest(),
        boundary='Nominal sampled model plus explicit guards; not measured antenna calibration or semantic training.')
    a.manifest.write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
