"""Generate the local Radar UI Bitmap Subset; no network or target board IO.

Run from any directory. The OFL font source is pinned in third_party/ui_font.
The source renderer is the character authority; review its output roles when
adding a new indirect string at a size other than the body size (18 pixels).
"""
from pathlib import Path
import argparse, hashlib, json, re
import PIL
from PIL import Image, ImageDraw, ImageFont, features
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "third_party/ui_font"
SOURCE = ROOT / "radar_runtime/src/display/radar_scope_view.c"
OUTPUT = ROOT / "radar_runtime/src/display/radar_font_zh_data.h"

def sha(data):
    return hashlib.sha256(data).hexdigest()

def strings(source):
    return [json.loads('"'+s+'"') for s in re.findall(r'"((?:[^"\\]|\\.)*)"', source)]

def function(source, name):
    begin = re.search(r"static [^{;]+\b"+name+r"\([^;]+?\)\s*\{", source)
    if not begin:
        raise ValueError("Missing role function: " + name)
    depth=1; end=begin.end()
    while depth:
        depth += (source[end]=='{')-(source[end]=='}'); end += 1
    return source[begin.end():end-1]

def character_roles(source):
    ascii_chars=set(chr(c) for c in range(32,127))
    roles={px:set(" ?") for px in (13,26,32)}
    roles[18]=set(ascii_chars)
    roles[20]=set("DP/1080P/60fps?")
    roles[18].update(''.join(s for s in strings(source) if any(ord(c)>127 for c in s)))
    # Indirect strings are the explicit exceptions to direct text(...size...).
    for name,px in (("reflection_state",13),("spatial_empty",26),("display_state",26)):
        roles[px].update(''.join(strings(function(source,name))))
    for line in source.splitlines():
        for size,px in ((1,13),(3,26),(4,32)):
            if re.search(r"(?:text|label)\([^;]*?,\s*"+str(size)+r"(?:U)?,",line):
                roles[px].update(''.join(strings(line)))
    # Strip source/control bytes; only visible characters have glyphs.
    return {px:{c for c in chars if ord(c)>=32} for px,chars in roles.items()}

def generate():
    source=SOURCE.read_text(encoding="utf-8")
    font_path=ASSET/"NotoSansCJKsc-Regular.otf"
    provenance=json.loads((ASSET/"provenance.json").read_text(encoding="utf-8"))
    for row in provenance["files"]:
        assert sha((ASSET/row["file"]).read_bytes())==row["sha256"],row["file"]
    cmap=TTFont(font_path).getBestCmap()
    roles=character_roles(source);data=bytearray();glyphs=[];coverage={}
    for px,chars in sorted(roles.items()):
        font=ImageFont.truetype(str(font_path),px,layout_engine=ImageFont.Layout.BASIC)
        top_origin=font.getbbox("国",anchor="la")[1]
        coverage[str(px)]=''.join(sorted(chars))
        for c in sorted(chars):
            assert ord(c) in cmap, f"Font has no U+{ord(c):04X}"
            left,top,right,bottom=font.getbbox(c,anchor="la")
            width,height=right-left,bottom-top
            advance=int(font.getlength(c)+0.5)
            if width and height:
                im=Image.new("L",(width,height))
                ImageDraw.Draw(im).text((-left,-top),c,font=font,fill=255,anchor="la")
                levels=[(p*15+127)//255 for p in im.tobytes()]
                packed=bytes((levels[i]<<4)|(levels[i+1] if i+1<len(levels) else 0) for i in range(0,len(levels),2))
            else:packed=b"";width=height=0
            offset=len(data);data.extend(packed)
            glyphs.append((ord(c),offset,len(packed),px,width,height,advance,left,top-top_origin))
    lines=["/* SPDX-License-Identifier: OFL-1.1",
           " * Radar UI Bitmap Subset; generated by tools/generate_ui_font.py.",
           " * Derived from Noto Sans CJK SC 2.004; copyright 2014-2021 Adobe.",
           " * See third_party/ui_font/LICENSE.txt and provenance.json.",
           " * Do not edit glyphs by hand. The renderer itself is MIT licensed."," */",
           "static const uint8_t radar_font_coverage[]={"]
    for i in range(0,len(data),24):lines.append(" "+",".join(str(n) for n in data[i:i+24])+",")
    lines += ["};","static const RadarFontGlyph radar_font_glyphs[]={"]
    lines.extend(" {"+",".join(str(n) for n in g)+"}," for g in glyphs)
    lines.append("};")
    header=('\n'.join(lines)+'\n').encode()
    manifest=dict(name="Radar UI Bitmap Subset",license="OFL-1.1",font_sha256=sha(font_path.read_bytes()),
        source_sha256=sha(SOURCE.read_bytes()),generated_sha256=sha(header),generator_sha256=sha(Path(__file__).read_bytes()),
        pillow=PIL.__version__,freetype=features.version("freetype2"),format="4bpp coverage, high nibble first, cropped glyphs",
        source_font_version="Noto Sans CJK SC Regular 2.004",coverage=coverage,glyph_count=len(glyphs),
        coverage_bytes=len(data),glyph_table_bytes=len(glyphs)*16,total_asset_bytes=len(data)+len(glyphs)*16,
        body_px=18,roles="13 reflection states; 18 body; 20 DP; 26 headings/status; 32 page title")
    assert manifest['total_asset_bytes']<130*1024,manifest['total_asset_bytes']
    return header,manifest

def main():
    parser=argparse.ArgumentParser();parser.add_argument("--check",action="store_true");args=parser.parse_args()
    header,manifest=generate();manifest_path=ASSET/"subset_manifest.json"
    if args.check:
        assert OUTPUT.read_bytes()==header,"Generated font header is stale"
        assert json.loads(manifest_path.read_text(encoding="utf-8"))==manifest,"Font manifest is stale"
    else:
        OUTPUT.write_bytes(header);manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding="utf-8")
    print(json.dumps({k:manifest[k] for k in ("glyph_count","coverage_bytes","total_asset_bytes")}) )

if __name__=="__main__":main()
